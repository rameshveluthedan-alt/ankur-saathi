"""
Ankur Saathi — export imported anchors to a seed file.

import_anchors.py --apply changes only the database it connects to. A fresh database built
by db/setup.sh would not have those anchors. This script writes every anchor that was added
or edited through the importer into a SQL seed file that setup.sh loads, so the whole bank
can be recreated from the repository.

    python scripts/export_anchors.py --env-file backend/.env
    python scripts/export_anchors.py --env-file backend/.env --check     # is the file up to date?

The output is deterministic (sorted, no timestamps), so it shows clean diffs in git.
Anchors edited from the original seed are included too: the file is loaded AFTER the base
seed with ON CONFLICT DO UPDATE, so the edited version wins.

Requires: pip install asyncpg
"""

import argparse
import asyncio
import sys
from pathlib import Path

import anchor_common as ac

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "db" / "seeds" / "content" / "04_imported_anchors.sql"

COLUMNS = ["id", "title_en", "title_hi", "description_en", "template_body",
           "primary_competency_ids", "secondary_competency_ids", "domain_id", "grade_range",
           "min_children", "max_children", "duration_minutes", "theme", "setting",
           "requires_print", "requires_tlm", "tlm_ids", "source", "validated_by", "is_active"]


def lit(v) -> str:
    """Python value -> SQL literal (always escaped: safe for apostrophes, backslashes, Hindi, newlines)."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (list, tuple)):
        return ("ARRAY[" + ",".join(lit(x) for x in v) + "]::text[]") if v else "ARRAY[]::text[]"
    t = str(v).replace("'", "''")
    if "\\" in t:                      # E'' strings interpret backslashes the same way on every server setting
        return "E'" + t.replace("\\", "\\\\") + "'"
    return "'" + t + "'"


def build_sql(rows) -> str:
    out = [
        "-- ============================================================================",
        "-- Ankur Saathi — imported anchor activities",
        "-- GENERATED by scripts/export_anchors.py. Do not edit by hand: change the spreadsheet,",
        "-- re-run import_anchors.py, then re-run export_anchors.py.",
        f"-- {len(rows)} anchor(s) added or edited through the importer: " + ", ".join(r["id"] for r in rows),
        "-- Loaded by db/setup.sh after the base content seeds. ON CONFLICT DO UPDATE means an",
        "-- edited original anchor replaces the version in 01_anchors_tlm.sql.",
        "-- Contains Hindi text: load with the client encoding set to UTF-8",
        "--   (PowerShell: $env:PGCLIENTENCODING = \"UTF8\").",
        "-- ============================================================================",
        "",
        "ALTER TABLE anchor_activities ADD COLUMN IF NOT EXISTS validated_by TEXT;",
        "ALTER TABLE anchor_activities ADD COLUMN IF NOT EXISTS imported_at TIMESTAMPTZ;",
        "",
    ]
    update_set = ",\n  ".join(f"{c} = EXCLUDED.{c}" for c in COLUMNS if c != "id")
    for r in rows:
        values = ", ".join(lit(r[c]) for c in COLUMNS)
        out.append(f"INSERT INTO anchor_activities ({', '.join(COLUMNS)}, imported_at)")
        out.append(f"VALUES ({values}, NOW())")
        out.append(f"ON CONFLICT (id) DO UPDATE SET\n  {update_set},\n  imported_at = NOW();")
        out.append("")
    ids = ", ".join(lit(r["id"]) for r in rows)
    out += [
        "UPDATE anchor_activities SET search_text = to_tsvector('simple',",
        "  coalesce(title_en,'') || ' ' || coalesce(description_en,'') || ' ' || coalesce(theme,'') || ' ' ||",
        "  coalesce(setting,'') || ' ' || array_to_string(primary_competency_ids, ' ') || ' ' ||",
        "  coalesce(array_to_string(secondary_competency_ids, ' '), ''))",
        f"WHERE id IN ({ids});",
        "",
    ]
    return "\n".join(out)


async def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", default=str(DEFAULT_OUT), help=f"default {DEFAULT_OUT.relative_to(ROOT)}")
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the file is missing or differs from the database")
    ac.add_db_args(ap)
    args = ap.parse_args()

    db = await ac.connect(args)
    has_marker = await db.fetchval(
        "SELECT count(*) FROM information_schema.columns WHERE table_name='anchor_activities' AND column_name='imported_at'")
    rows = []
    if has_marker:
        rows = await db.fetch(f"SELECT {', '.join(COLUMNS)} FROM anchor_activities WHERE imported_at IS NOT NULL ORDER BY id")
    await db.close()

    out = Path(args.out)
    if not rows:
        print("No anchors have been imported into this database, so there is nothing to export.")
        print("(Run import_anchors.py --apply first.)")
        sys.exit(1 if args.check and out.exists() else 0)

    sql = build_sql(rows)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current == sql:
            print(f"UP TO DATE: {out} matches the {len(rows)} imported anchor(s) in the database.")
            return
        print(f"OUT OF DATE: {out} {'does not exist' if current is None else 'differs from the database'}."
              f" Run export_anchors.py to refresh it.")
        sys.exit(1)

    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(sql)
    print(f"Wrote {len(rows)} anchor(s) to {out}")
    for r in rows:
        print(f"  {r['id']}  {r['title_en']}")
    print("Commit this file together with the validated spreadsheet.")


if __name__ == "__main__":
    asyncio.run(main())
